using Npgsql;
namespace VetClinic.Infrastructure;

public static class ErrorTranslator
{
    public static string Translate(Exception ex) => ex switch
    {
        PostgresException pg => TranslatePostgres(pg),
        NpgsqlException => "Не вдалося звернутися до бази даних. Перевірте, чи запущено PostgreSQL і чи правильний рядок підключення (змінна VETCLINIC_CONNECTION).",
        InvalidOperationException io => "Помилка роботи застосунку: " + io.Message,
        _ => "Сталася непередбачена помилка: " + ex.Message
    };

    private static string TranslatePostgres(PostgresException pg) => pg.SqlState switch
    {
        "P0001" => pg.MessageText,
        "23P01" => "Цей час недоступний: у лікаря вже є прийом, що перетинається з вибраним проміжком.",
        "23503" => "Посилання на неіснуючий запис: перевірте ID (порода, власник, тварина, лікар тощо).",
        "23505" => "Такий запис уже існує (порушено унікальність даних, наприклад номер чипа чи рахунок для прийому).",
        "23514" => "Значення не відповідає обмеженням бази даних (наприклад, кінець прийому має бути пізніше за початок).",
        "23502" => "Не заповнено обов'язкове поле.",
        "22P02" => "Неправильний формат значення.",
        "28P01" => "Невірне ім'я користувача або пароль PostgreSQL.",
        "3D000" => "Базу даних не знайдено. Перевірте назву бази у рядку підключення.",
        "42P01" => "Не знайдено таблицю чи view. Імовірно, не виконано всі SQL-скрипти (01–03, 05–07).",
        "42883" => "Не знайдено функцію чи процедуру. Імовірно, не виконано всі SQL-скрипти (01–03, 05–07).",
        _ => $"Помилка бази даних ({pg.SqlState}): {pg.MessageText}"
    };
}
